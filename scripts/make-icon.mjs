// Draws the app icon from the real map shapes: Croatia in ink on atlas paper, red dot on Zagreb.
// Writes assets/icon-only.png, icon-foreground.png, icon-background.png (1024px) for @capacitor/assets.
// Run: node scripts/make-icon.mjs
import fs from 'fs';
import path from 'path';
import sharp from 'sharp';

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
globalThis.window = {};
await import(path.join(root, 'www', 'data.js'));
const { bbox, croatia, islands } = window.MAP_DATA;

const PAPER = '#f3ead3', INK = '#2b2620', RED = '#b5361f';
const LAT0 = 44.5, LON0 = 16.5, KX = 111.32 * Math.cos(LAT0 * Math.PI / 180), KY = 110.57;
const zagreb = [(15.982 - LON0) * KX, (LAT0 - 45.815) * KY];

// fill: share of the 1024px canvas the map should span (Android adaptive icons crop the edges).
function svg({ fill, background }) {
  const [x0, y0, x1, y1] = bbox;
  const size = Math.max(x1 - x0, y1 - y0);
  const s = (1024 * fill) / size;
  const tx = 512 - ((x0 + x1) / 2) * s, ty = 512 - ((y0 + y1) / 2) * s;
  return `<svg xmlns="http://www.w3.org/2000/svg" width="1024" height="1024" viewBox="0 0 1024 1024">
    ${background ? `<rect width="1024" height="1024" fill="${PAPER}"/>` : ''}
    <g transform="translate(${tx} ${ty}) scale(${s})">
      <path d="${croatia}${islands}" fill="${INK}"/>
      <circle cx="${zagreb[0]}" cy="${zagreb[1]}" r="${34 / s}" fill="${PAPER}"/>
      <circle cx="${zagreb[0]}" cy="${zagreb[1]}" r="${22 / s}" fill="${RED}"/>
    </g>
  </svg>`;
}

const out = path.join(root, 'assets');
fs.mkdirSync(out, { recursive: true });
const png = (s, file) => sharp(Buffer.from(s)).png().toFile(path.join(out, file));
await png(svg({ fill: 0.78, background: true }), 'icon-only.png');
await png(svg({ fill: 0.56, background: false }), 'icon-foreground.png');
await png(`<svg xmlns="http://www.w3.org/2000/svg" width="1024" height="1024"><rect width="1024" height="1024" fill="${PAPER}"/></svg>`, 'icon-background.png');
// Launch screen (used for iPhone): paper background with the map small in the middle.
const splash = svg({ fill: 0.78, background: true }).replace('width="1024" height="1024" viewBox="0 0 1024 1024"', 'width="2732" height="2732" viewBox="-854 -854 2732 2732"').replace('<rect width="1024" height="1024"', '<rect x="-854" y="-854" width="2732" height="2732"');
await png(splash, 'splash.png');
await png(splash, 'splash-dark.png');
console.log('icons written to assets/');

// Android adaptive icon as a vector (sharp at any size, also used on the launch screen).
// Viewport is 108x108 like the adaptive icon; Android shows the inner ~72, so the map fits in 62.
function vectorPath(d, scale, tx, ty, minStep) {
  let out = '';
  for (const ring of d.split('Z').filter(Boolean)) {
    const pts = ring.replace(/^M/, '').split('L').map(p => p.trim().split(' ').map(Number))
      .map(([x, y]) => [x * scale + tx, y * scale + ty]);
    const kept = [pts[0]];
    for (const p of pts.slice(1)) {
      const q = kept[kept.length - 1];
      if (Math.hypot(p[0] - q[0], p[1] - q[1]) >= minStep) kept.push(p);
    }
    if (kept.length < 4) continue; // too small to see at icon size
    out += 'M' + kept.map(([x, y]) => x.toFixed(2) + ',' + y.toFixed(2)).join('L') + 'Z';
  }
  return out;
}
const [bx0, by0, bx1, by1] = bbox;
const vs = 62 / Math.max(bx1 - bx0, by1 - by0);
const vtx = 54 - ((bx0 + bx1) / 2) * vs, vty = 54 - ((by0 + by1) / 2) * vs;
const zx = zagreb[0] * vs + vtx, zy = zagreb[1] * vs + vty;
const circle = r => `M${(zx - r).toFixed(2)},${zy.toFixed(2)}a${r},${r} 0 1,0 ${2 * r},0a${r},${r} 0 1,0 ${-2 * r},0Z`;
const vector = `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by scripts/make-icon.mjs. Do not edit. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp" android:height="108dp"
    android:viewportWidth="108" android:viewportHeight="108">
    <path android:fillColor="${INK}" android:pathData="${vectorPath(croatia + islands, vs, vtx, vty, 0.25)}"/>
    <path android:fillColor="${PAPER}" android:pathData="${circle(3.4)}"/>
    <path android:fillColor="${RED}" android:pathData="${circle(2.2)}"/>
</vector>
`;
const res = path.join(root, 'android', 'app', 'src', 'main', 'res');
fs.writeFileSync(path.join(res, 'drawable', 'ic_launcher_map.xml'), vector);
console.log('vector icon written,', (vector.length / 1024).toFixed(0) + 'KB');
